def _journal_matches(value, transition: str, candidate: dict) -> bool:
    if isinstance(value, str):
        return value.replace("-", "_") in TRANSITION_MARKERS[transition]
    if isinstance(value, list):
        return any(_journal_matches(v, transition, candidate) for v in value)
    if isinstance(value, dict):
        if field(candidate, "candidate_id") and "candidate_id" in value and value["candidate_id"] != field(candidate, "candidate_id"):
            return False
        return any(_journal_matches(value.get(key), transition, candidate)
                   for key in ("journal_state", "transition", "stage", "state"))
    return False


def _journal_files(kinbase: Kinbase, repo: Path) -> tuple[Path, ...]:
    roots = [repo / ".kin" / "local" / "journal"]
    config = kinbase.xdg_config_home / "kinbase" / "config.toml"
    if config.is_file():
        personal = tomllib.loads(config.read_text())["personal"]["data_root"]
        private = Path(personal)
        roots.append(private / "journal")
        roots.extend(p for p in private.rglob("journal") if p.is_dir())
    return tuple(sorted({p for root in roots for p in root.rglob("*") if p.is_file()}))


def _journal_snapshot(kinbase: Kinbase, repo: Path, candidate: dict,
                      transition: str) -> dict[str, str]:
    observed = {}
    for path in _journal_files(kinbase, repo):
        try:
            raw = path.read_bytes()
        except FileNotFoundError:  # Atomic journal rename during polling.
            continue
        try:
            value = json.loads(raw)
        except (ValueError, UnicodeDecodeError):
            value = raw.decode("utf-8", errors="replace").strip()
        if isinstance(value, dict) and field(candidate, "candidate_id") and "candidate_id" in value and value["candidate_id"] != field(candidate, "candidate_id"):
            continue
        if _journal_matches(value, transition, candidate) or _journal_matches(path.stem, transition, candidate):
            observed[str(path)] = hashlib.sha256(raw).hexdigest()
    return observed


def _journal_status(kinbase: Kinbase, repo: Path, candidate: dict, transition: str):
    status = kinbase.run("status", "--repo", str(repo), "--json", cwd=repo, check=False)
    value = field(status.json, "journal_state")
    return value if _journal_matches(value, transition, candidate) else None


def _kill_at_transition(kinbase: Kinbase, world, candidate: dict,
                        destination: str, transition: str) -> dict:
    """Start a fan-out and kill it once the transition's artefact appears.

    The kill point is *witnessed*, not timed: the harness polls the store for
    the artefact class the transition produces and only then signals the
    process. The witness records the observed artefact, the signal sent and the
    observed exit status, so a run in which the process finished normally cannot
    be reported as an interrupted transition.
    """
    repo = world.repo.path
    before = _journal_snapshot(kinbase, repo, candidate, transition)
    prior_state = _journal_status(kinbase, repo, candidate, transition)
    process = kinbase.popen("session", "observe", candidate["session_id"],
                            "--event", candidate["corpus"], "--json", cwd=repo)
    witness = Witness(kind="crash:" + transition)
    deadline = time.monotonic() + 20.0
    appeared = False
    observed = {}
    last_status = time.monotonic()
    while time.monotonic() < deadline:
        now = _journal_snapshot(kinbase, repo, candidate, transition)
        changed = {p: digest for p, digest in now.items() if before.get(p) != digest}
        if changed:
            appeared = True
            observed = {"journal_markers": changed}
            break
        if process.poll() is not None:
            break
        if time.monotonic() - last_status >= 0.05:
            state = _journal_status(kinbase, repo, candidate, transition)
            last_status = time.monotonic()
            if state is not None and state != prior_state:
                appeared = True
                observed = {"journal_state": state}
                break
        time.sleep(0.001)
    signal_sent = False
    if process.poll() is None:
        try:
            process.send_signal(signal.SIGKILL)
            signal_sent = True
        except ProcessLookupError:
            pass  # A completed transaction is not an interrupted transition.
    try:
        process.communicate(timeout=30)
    except subprocess.TimeoutExpired:
        process.kill()
        process.communicate(timeout=30)
    exit_witness = witness_process_exit(process, "crash:" + transition)
    witness.note(transition=transition, artefact_observed=appeared,
                 observation=observed, signal_sent=signal_sent,
                 exit_status=process.returncode)
    return {
        "transition": transition,
        "crash_witnessed": bool(appeared and signal_sent and process.returncode == -signal.SIGKILL),
        "witness": witness.as_json(),
        "exit_witness": exit_witness.as_json(),
    }


@contextlib.contextmanager
def _crash_world(kinbase: Kinbase, roots: ProofRoots, transition: str):
    """Each kill needs a fresh transaction, not the preceding probe's receipt."""
    layout = ProofRoots.create(roots.run_root / "crash-probes" / transition)
    driver = Kinbase(home=layout.home, xdg_config_home=layout.xdg_config_home,
                      cwd=layout.repo_root, path_prefix=kinbase.path_prefix)
    world = SignedWorld.create(layout.repo_root)
    service = start_company(driver, layout)
    try:
        anchors = trust.establish(driver, layout, world, start_service=service,
                                  classifier_model="ollama:qwen2.5:7b")
        trust.classifier_pinned(anchors, what="V-2 crash recovery")
        yield driver, world, anchors
    finally:
        service.stop()


def _one_fanout_source(corpus, repo):
    # Fixture selection uses held-out gold only inside the tester boundary.
    # The shipping process receives one native message, with no destination hint.
    tokens = {token for token, gold in corpus.gold.items()
              if "company" in gold["destinations"]
              and sum("codebase" in atom[2] for atom in gold["atoms"]) == 1}
    source = next((json.loads(line) for line in corpus.path.read_text().splitlines()
                   if json.loads(line)["id"] in tokens), None)
    if source is None:
        raise prereq.missing("fixture", "single-fanout", "one Codebase atom and Company evidence required")
    path = repo.parent / "one-fanout.jsonl"
    path.write_text(json.dumps(source) + "\n")
    return path


@spec_ref(
    VERIFY("V-2", "crash-recovery",
           "Kill each destination between nonce reservation, event append/rename, manifest, "
           "receipt, and apology transitions, then retry concurrently."),
)
def test_kill_at_every_transition_then_concurrent_retry(
    kinbase: Kinbase, roots: ProofRoots, held_out
) -> None:
    results = []
    for transition in TRANSITIONS:
        with _crash_world(kinbase, roots, transition) as (driver, world, anchors):
            session = start_session(driver, world.repo.path)
            candidate = {"session_id": session, "corpus": str(_one_fanout_source(held_out, world.repo.path))}
            destination = "codebase:" + anchors.repository_uuid
            with contextlib.ExitStack() as perturbation:
                if transition == "apology":
                    from ._harness.service import Blackhole
                    blackhole = perturbation.enter_context(Blackhole(0))
                    perturbation.enter_context(anchors.company_endpoint(
                        f"http://127.0.0.1:{blackhole.port}"))
                    destination = "company:root"
                killed = _kill_at_transition(driver, world, candidate, destination, transition)
                first = _checkpoint_async(driver, world.repo.path, candidate, destination)
                second = _checkpoint_async(driver, world.repo.path, candidate, destination)
                first.communicate(timeout=120)
                second.communicate(timeout=120)
                status = _admissions(driver, world.repo.path, session)
                killed.update({
                    "duplicate_events": field(status, "duplicate_events"),
                    "recursive_apologies": field(status, "recursive_apologies"),
                    "recovered": field(status, "fanout_receipts", "codebase", "state")
                    == "committed",
                    "total_events_after_recovery": field(status, "committed_event_count"),
                })
        results.append(killed)

    require_all(
        results, lambda r: r["crash_witnessed"], obligation="V-2.crash-recovery",
        why="each named transition must actually have been interrupted",
        minimum=len(TRANSITIONS), origin=Origin.HARNESS,
    )
    require_all(
        results, lambda r: r["total_events_after_recovery"] == 1,
        obligation="V-2.crash-recovery", minimum=len(TRANSITIONS),
        why="each independent crash probe leaves exactly one event",
        origin=Origin.PRODUCT,
    )
    O.check(
        "V-2.crash-recovery",
        {
            "transitions": results,
            "total_events_after_recovery": results[-1]["total_events_after_recovery"],
        },
        label="witnessed kill at each transition, then concurrent retry",
    )


