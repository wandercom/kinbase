def _receipt_row(status: dict, key: str) -> dict:
    row = {
        "destination": key,
        "state": field(status, "fanout_receipts", key, "state"),
    }
    rollback = field(status, "fanout_receipts", key, "global_rollback")
    if rollback is not None:
        row["global_rollback"] = rollback
    return row
