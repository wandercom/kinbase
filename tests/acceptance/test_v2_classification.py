"""V-2 --- classification and fan-out (`P-2`, Critical).

Detector Reviewer finding 12 named four defects, all fixed here.

*No calibration corpus.* ``routing_corpus.json`` pointed at a manifest that did
not exist, so the calibration obligation passed on a refusal. The excluded
60-message corpus and its manifest are now committed, deterministically
generated by ``tests/tools/freeze-calibration.py``, digest bound, and proved
disjoint from the held-out corpus.

*Product-reported metrics.* Every number came out of the system under test. The
product now supplies only raw per-message predictions under opaque identifiers;
:mod:`acceptance._harness.metrics` joins them to Tester-held gold and computes
macro-F1, per-label precision/recall/F1, shared precision, exact-match
atomisation, private-to-shared detection and abstention itself. The product's
predictions are scored only by the instrument (Validator R-13).

*Pre-opaque identifiers.* Mixed-message lookups used the frozen ``m###`` ids, so
an implementation could memorise the answer key. Every lookup now goes through
the per-run opaque token.

*Sleep-duration crash seams.* The five kill points were labels with a hardcoded
recovery flag. Each transition is now killed at a witnessed point --- an
observed artefact appearing under the store, followed by an observed abnormal
process exit --- and recovery is read back from the store, never reported.
"""

