def _observe(kinbase: Kinbase, repo: Path, corpus: Path, session: str) -> dict:
    """Drive one classifier run over a bound corpus through the real surface."""
    result = kinbase.run(
        "session", "observe", session, "--event", str(corpus), "--json",
        cwd=repo, check=False,
    )
    if result.returncode == 1:
        raise ProductFailure("`session observe` returned the reserved exit 1")
    payload = result.json
    if not isinstance(payload, dict):
        raise ProductFailure("`session observe --json` did not return an object")
    if result.returncode == 0:
        trust.verify_classifier_spawn(kinbase, repo)
    return payload


def _admissions(kinbase: Kinbase, repo: Path, session: str) -> dict:
    """Read private audit records; compute counts from bytes, never a product verdict."""
    from ._harness.admission import audit
    return audit(kinbase, repo, session)


def _run_pool(kinbase: Kinbase, repo: Path, corpus, *, runs: int,
              label: str) -> tuple[list, list[dict]]:
    """Execute the preregistered runs and join each to Tester-held gold."""
    gold = metrics.parse_gold(corpus.gold)
    joins = []
    reported: list[dict] = []
    for index in range(runs):
        session = start_session(kinbase, repo)
        observed = _observe(kinbase, repo, corpus.path, session)
        listing = _admissions(kinbase, repo, session)
        predictions = metrics.parse_predictions(field(listing, "predictions"))
        joins.append(metrics.joined(predictions, gold,
                                    name=label + "-run-" + str(index)))
        reported.append({
            "run": index,
            "model_fingerprint": field(observed, "classifier", "fingerprint"),
            "macro_f1": joins[-1].macro_f1(),
        })
    return joins, reported


def _first_candidate(listing: dict, destination: str | None = None) -> dict:
    candidates = [c for c in rows(listing, "candidates")
                  if destination is None or field(c, "destination") == destination]
    if not candidates:
        raise ProductFailure(
            "the private audit ledger has no candidate for the required destination"
        )
    return candidates[0]



def _fanout_pair(listing: dict, destination: str) -> tuple[dict, dict]:
    for local in rows(listing, "candidates"):
        if field(local, "destination") != destination or not isinstance(field(local, "message_id"), str):
            continue
        for company in rows(listing, "candidates"):
            if field(company, "destination") == "company:root" and field(
                    company, "message_id") == field(local, "message_id"):
                if field(local, "candidate_id") != field(company, "candidate_id"):
                    return local, company
    raise ProductFailure("V-2 fan-out requires independent Codebase and Company "
                         "candidates for the same source message")

def _checkpoint(kinbase: Kinbase, repo: Path, candidate: dict, destination: str, **kwargs):
    return kinbase.run("session", "checkpoint", str(field(candidate, "session_id")),
                       "--json", cwd=repo, check=False, **kwargs)


def _checkpoint_async(kinbase: Kinbase, repo: Path, candidate: dict, destination: str):
    return kinbase.popen("session", "checkpoint", str(field(candidate, "session_id")),
                         "--json", cwd=repo)


